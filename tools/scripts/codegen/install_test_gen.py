"""
Generates the install-test compilation test that verifies every generated
client header is includable, and patches CMakeLists.txt to build it.

To keep compile times low, the ~400 client-header includes are spread across
several translation units (see NUM_BUCKETS) instead of one enormous file, so
the build tool compiles them in parallel. This matters most for
CUSTOM_MEMORY_MANAGEMENT builds, where Aws:: container types are distinct
template instantiations and a single all-in-one translation unit is very slow.
"""

import argparse
import os
import re
import shutil
from pathlib import Path
from typing import List, Optional, Set

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
GENERATED_SRC = os.path.normpath(os.path.join(SCRIPT_DIR, "../../../generated/src"))
INSTALL_TEST_DIR = os.path.normpath(os.path.join(SCRIPT_DIR, "../../CI/install-test"))
OUTPUT_CPP = os.path.join(INSTALL_TEST_DIR, "all_services_test.cpp")
PARTS_DIRNAME = "all_services_test_parts"
PARTS_DIR = os.path.join(INSTALL_TEST_DIR, PARTS_DIRNAME)
CMAKE = os.path.join(INSTALL_TEST_DIR, "CMakeLists.txt")

GENERATED_BLOCK_START = "# -- all_services_test build target --"

# Number of translation units to spread the client-header includes across.
# Chosen to comfortably exceed the core count of the build hosts so the compile
# fully parallelizes; capped at the header count for small (subset) builds.
NUM_BUCKETS = 64


class InstallTestGen(object):

    def __init__(self, debug: bool, **kwargs):
        self.debug = debug

    def generate(self, clients_to_build: Optional[Set[str]]):
        """Generate install tests for the given client list

        :param clients_to_build: Set of client names to generate tests for
        :return: 0 if success, non-zero otherwise
        """
        try:
            client_list = clients_to_build if clients_to_build else None
            headers = self._find_client_headers(client_list)
            components = [self._sdk_component(h) for h in headers]
            sources = self._write_cpp(headers)
            self._patch_cmake(components, sources)

            if self.debug:
                if client_list:
                    print(f"Generated compilation test for {len(headers)} clients: {', '.join(client_list)}")
                else:
                    print(f"Generated compilation test for all {len(headers)} clients")
            return 0
        except Exception as e:
            if self.debug:
                print(f"Error generating install tests: {e}")
            return -1

    def _find_client_headers(self, client_list: Optional[Set[str]] = None) -> List[str]:
        headers = []
        for path in Path(GENERATED_SRC).rglob("*Client.h"):
            parts = path.parts
            if "include" not in parts:
                continue
            header_path = "/".join(parts[parts.index("include") + 1:])
            if client_list:
                service_name = self._sdk_component(header_path)
                if service_name and service_name in client_list:
                    headers.append(header_path)
            else:
                headers.append(header_path)
        return sorted(headers)

    def _sdk_component(self, header: str) -> Optional[str]:
        # "aws/s3-crt/S3CrtClient.h" -> "s3-crt"
        parts = header.split("/")
        return parts[1] if len(parts) >= 3 else None

    def _write_cpp(self, headers: List[str]) -> List[str]:
        """Write the compilation test, split across up to NUM_BUCKETS translation units.

        The main translation unit holds only ``main()``; the client-header
        includes are round-robin distributed across the part files so that a few
        large services do not all land in the same (slow) translation unit.

        :return: CMake-relative paths of every generated source file.
        """
        banner = [
            "// Auto-generated by install_test_gen.py — do not edit manually.",
            "// Compilation-only test: verifies every generated client header is includable.",
            "",
        ]

        # Main translation unit: entry point only, no service headers.
        main_lines = banner + [
            "#include <iostream>",
            "#include <aws/core/Aws.h>",
            "",
            "int main() {",
            "    Aws::SDKOptions options;",
            "    Aws::InitAPI(options);",
            "    std::cout << \"Compilation test succeeded\\n\";",
            "    Aws::ShutdownAPI(options);",
            "    return 0;",
            "}",
            "",
        ]
        with open(OUTPUT_CPP, "w") as f:
            f.write("\n".join(main_lines))

        # Recreate the parts directory from scratch so stale files never linger
        # (e.g. when regenerated for a smaller subset of clients).
        if os.path.isdir(PARTS_DIR):
            shutil.rmtree(PARTS_DIR)
        os.makedirs(PARTS_DIR, exist_ok=True)

        sources = ["all_services_test.cpp"]
        num_buckets = min(NUM_BUCKETS, len(headers)) or 1
        buckets: List[List[str]] = [[] for _ in range(num_buckets)]
        for i, header in enumerate(headers):
            buckets[i % num_buckets].append(header)

        for idx, bucket in enumerate(buckets):
            if not bucket:
                continue
            part_lines = banner + ["#include <aws/core/Aws.h>"]
            part_lines += [f"#include <{h}>" for h in bucket]
            part_lines.append("")
            fname = f"all_services_test_part{idx:03d}.cpp"
            with open(os.path.join(PARTS_DIR, fname), "w") as f:
                f.write("\n".join(part_lines))
            sources.append(f"{PARTS_DIRNAME}/{fname}")

        if self.debug:
            print(f"Wrote {OUTPUT_CPP} and {len(sources) - 1} part file(s) "
                  f"for {len(headers)} headers under {PARTS_DIR}")
        return sources

    def _patch_cmake(self, components: List[Optional[str]], sources: List[str]) -> None:
        comp_list = " ".join(sorted(set(filter(None, components))))
        sources_block = "\n".join(f"        {s}" for s in sources)
        block = (
            f"{GENERATED_BLOCK_START}\n"
            f"find_package(AWSSDK REQUIRED COMPONENTS core {comp_list})\n"
            f"add_executable(all_services_test\n"
            f"{sources_block}\n"
            f")\n"
            f"target_link_libraries(all_services_test ${{AWSSDK_LINK_LIBRARIES}})\n"
            f"target_include_directories(all_services_test PRIVATE ${{AWSSDK_INCLUDE_DIRS}})\n"
        )
        with open(CMAKE, "r") as f:
            content = f.read()

        pattern = re.compile(
            re.escape(GENERATED_BLOCK_START) + r".*?(?=\n# |\Z)",
            re.DOTALL,
        )
        if pattern.search(content):
            content = pattern.sub(block, content)
        else:
            content = content.rstrip("\n") + "\n\n" + block + "\n"

        with open(CMAKE, "w") as f:
            f.write(content)
        if self.debug:
            print(f"Patched {CMAKE}")

def parse_arguments():
    parser = argparse.ArgumentParser(description="Generate compilation test for AWS SDK C++ clients")
    parser.add_argument("--client_list", type=str, help="Comma-separated or semi-colon-separated list of SDK clients")
    return parser.parse_args()

if __name__ == "__main__":
    args = parse_arguments()
    client_list = None
    if args.client_list:
        client_list = args.client_list.replace(";", ",").split(",")
        client_list = [c.strip() for c in client_list if c.strip()]

    install_test_gen = InstallTestGen(debug=True)
    exit_code = install_test_gen.generate(client_list)
    exit(exit_code)
